const ACTIVE = ["diagnosing", "patch_ready", "qa_passed", "approval", "payment"];

function computeKpis(
  tickets: { status: string; approval_required?: boolean | null }[],
  payments: { amount: number | null; status: string | null }[],
) {
  return {
    leads: tickets.filter((t) => t.status === "new" || t.status === "qualified").length,
    active: tickets.filter((t) => ACTIVE.includes(t.status)).length,
    revenue: payments.filter((p) => p.status !== "failed").reduce((s, p) => s + (p.amount ?? 0), 0),
    approvals: tickets.filter((t) => t.approval_required && t.status === "approval").length,
  };
}

async function getKpis() {
  if (isSupabaseConfigured) {
    const sb = getSupabaseServer();
    if (sb) {
      const [t, p] = await Promise.all([
        sb.from("tickets").select("status, approval_required"),
        sb.from("payments").select("amount, status"),
      ]);
      return computeKpis(t.data ?? [], p.data ?? []);
    }
  }
  return computeKpis(DEMO_TICKETS, DEMO_PAYMENTS);
}

